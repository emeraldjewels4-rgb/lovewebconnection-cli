#!/usr/bin/env node
// Writes web9999/networks.json, the chain table the page fetches as networks.json beside itself.
//
// WHERE IT BELONGS
//
// In the bundle, beside index.html - not in the proxy rule. The page asks for it same-origin,
// and it is a file this repository generates, so the deploy already puts it on the server. A
// proxy rule for /web9999/* would ask x10 for a file x10 never had, and would make the site
// depend on a second host for its own chain list. The proxy forwards /api/* only.
//
// WHERE IT COMES FROM
//
// CHAIN_PRESETS in src/chain.ts, read through the built dist/chain.js so the file always
// describes the presets this build of the kit ships. Nothing here is hand-maintained: edit the
// presets, rebuild, regenerate.
//
//   node deploy/networks.mjs           write web9999/networks.json
//   node deploy/networks.mjs --check   exit 1 if the file on disk disagrees with the presets
//
// Exit codes: 0 written (or already current), 1 --check found a difference, 2 nothing to read.
//
// Everything is written to stdout: deploy-web9999.ps1 runs this with
// $ErrorActionPreference = 'Stop', where a native command's stderr becomes a terminating error.
import { existsSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const builtPath = path.join(root, 'dist', 'chain.js');
const sourcePath = path.join(root, 'src', 'chain.ts');
const outPath = path.join(root, 'web9999', 'networks.json');
const check = process.argv.includes('--check');

if (!existsSync(builtPath)) {
  console.log(`  no build at ${path.relative(root, builtPath)}: run npm run build first`);
  process.exit(2);
}
if (existsSync(sourcePath) && statSync(sourcePath).mtimeMs > statSync(builtPath).mtimeMs) {
  console.log('  note: src/chain.ts is newer than dist/chain.js, so these presets may lag the source; npm run build refreshes them');
}

const { CHAIN_PRESETS } = await import(pathToFileURL(builtPath).href);
const presets = Object.values(CHAIN_PRESETS ?? {});
if (presets.length === 0) {
  console.log('  no presets in dist/chain.js: nothing to write');
  process.exit(2);
}

// chainId is hex because that is what the page compares against: it reads eth_chainId's result
// and tests `reported === network.chainId.toLowerCase()`, where reported is the node's raw
// "0x..." answer. A decimal id there would report every healthy chain as the wrong chain.
// The decimal form travels alongside it, for humans reading the file.
const networks = presets
  .map((preset) => ({
    name: preset.name,
    symbol: preset.nativeSymbol,
    chainId: `0x${preset.chainId.toString(16)}`,
    chainIdDecimal: preset.chainId,
    rpcUrl: preset.rpcUrl,
    fallbackRpcUrl: preset.fallbackRpcUrl,
  }))
  .sort((a, b) => a.chainIdDecimal - b.chainIdDecimal);

const payload = {
  note: 'Generated by deploy/networks.mjs from CHAIN_PRESETS in src/chain.ts. Do not edit by hand.',
  networks,
};
const text = `${JSON.stringify(payload, null, 2)}\n`;
const summary = `${networks.length} networks (${networks.map((row) => `${row.name} ${row.chainIdDecimal} ${row.chainId}`).join(', ')})`;

const current = existsSync(outPath) ? readFileSync(outPath, 'utf8') : null;
const relative = path.relative(root, outPath).replace(/\\/g, '/');

if (check) {
  if (current === text) {
    console.log(`  networks.json matches the presets: ${summary}`);
    process.exit(0);
  }
  console.log(
    current === null
      ? `  ${relative} is missing: run node deploy/networks.mjs`
      : `  ${relative} disagrees with the presets: run node deploy/networks.mjs (presets: ${summary})`
  );
  process.exit(1);
}

if (current === text) {
  console.log(`  ${relative} already matches the presets: ${summary}`);
  process.exit(0);
}

writeFileSync(outPath, text);
console.log(`  wrote ${relative}: ${summary}`);
